#[test]
fn key_offset_past_the_table_is_refused() {
    assert!(RpCrypt::regist(Target::Ps5V1, &REGIST_AMBASSADOR_BRIGHT, 0x20, PIN).is_err());
    assert!(psr_crypto::rpcrypt::aeropause(Target::Ps5V1, 0x20, &REGIST_AMBASSADOR_BRIGHT).is_err());
}

#[test]
fn aeropause_and_ambassador_from_aeropause_round_trip() {
    for target in [Target::Ps4V10, Target::Ps5V1] {
        for off in [0, 7, 0x1f] {
            let aero = psr_crypto::rpcrypt::aeropause_psn(target, off, &REGIST_AMBASSADOR_BRIGHT).unwrap();
            let back = psr_crypto::rpcrypt::ambassador_from_aeropause(target, off, &aero).unwrap();
            assert_eq!(back, REGIST_AMBASSADOR_BRIGHT, "{target:?} offset {off}");
        }
    }
}

#[test]
fn encrypt_then_decrypt_round_trips_every_length() {
    let crypt = RpCrypt::regist(Target::Ps5V1, &REGIST_AMBASSADOR_BRIGHT, 3, PIN).unwrap();
    let data: Vec<u8> = (0..=200u8).collect();
    for len in 0..data.len() {
        let cipher = crypt.encrypt(42, &data[..len]);
        assert_eq!(crypt.decrypt(42, &cipher), &data[..len]);
    }
}

// Vectors from chiaki-ng's own C code, for the paths its tests don't cover (PS5 above all).
// See scripts/oracle/README.md.

fn hex16(s: &str) -> [u8; 16] {
    std::array::from_fn(|i| u8::from_str_radix(&s[i * 2..i * 2 + 2], 16).unwrap())
}

#[test]
fn matches_chiaki_ng_oracle_for_ps4_10_and_ps5() {
    let text = include_str!("vectors/rpcrypt_oracle.txt");
    let mut cases = 0;
    for line in text.lines().filter(|l| !l.starts_with('#') && !l.is_empty()) {
        let field = |k: &str| {
            line.split(' ')
                .find_map(|kv| kv.strip_prefix(k).and_then(|v| v.strip_prefix('=')))
                .unwrap_or_else(|| panic!("{k} missing in: {line}"))
        };
        let target = match field("target") {
            "1000" => Target::Ps4V10,
            "1000100" => Target::Ps5V1,
            other => panic!("unexpected target {other}"),
        };
        let case: u32 = field("case").parse().unwrap();
        let off: usize = field("off").parse().unwrap();
        let (nonce, morning) = (hex16(field("nonce")), hex16(field("morning")));
        let (bright, ambassador) = bright_ambassador(target, &nonce, &morning).unwrap();
        assert_eq!(bright, hex16(field("bright")), "{line}");
        assert_eq!(ambassador, hex16(field("ambassador")), "{line}");
        assert_eq!(psr_crypto::rpcrypt::aeropause(target, off, &ambassador).unwrap(), hex16(field("aeropause")));
        assert_eq!(
            psr_crypto::rpcrypt::aeropause_psn(target, off, &ambassador).unwrap(),
            hex16(field("aeropause_psn"))
        );
        let regist = RpCrypt::regist(target, &ambassador, off, 12_345_678 + case).unwrap();
        assert_eq!(*regist.bright(), hex16(field("regist_bright")), "{line}");
        assert_eq!(field("roundtrip"), "ok");
        cases += 1;
    }
    assert_eq!(cases, 8, "the oracle file should hold 4 cases for each of 2 targets");
}

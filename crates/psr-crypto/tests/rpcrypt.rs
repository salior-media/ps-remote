#[test]
fn iv_ps4_pre10_is_stable_per_counter() {
    let crypt = RpCrypt::auth(Target::Ps4V9, &NONCE_PRE10, &MORNING_PRE10).unwrap();
    let iv_a = [0x06, 0x29, 0xbe, 0x04, 0xe9, 0x91, 0x1c, 0x48, 0xb4, 0x5c, 0x02, 0x6d, 0xb7, 0xb7, 0x88, 0x46];
    let iv_b = [0x3f, 0xd0, 0x83, 0x0a, 0xc7, 0x30, 0xfc, 0x56, 0x75, 0x2d, 0xbe, 0xb8, 0x2c, 0x68, 0xa7, 0x04];
    assert_eq!(crypt.iv(0), iv_a);
    assert_eq!(crypt.iv(0), iv_a);
    assert_eq!(crypt.iv(COUNTER), iv_b);
    assert_eq!(crypt.iv(COUNTER), iv_b);
}

